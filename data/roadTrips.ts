export function getRoadTrip(slug: string): RoadTrip | undefined {
  return roadTrips.find((t) => t.slug === slug);
}

export const featuredTrips = roadTrips.filter((t) => t.featured);

export function tripsInRegion(regionSlug: string): RoadTrip[] {
  return roadTrips.filter((t) => t.regionSlugs.includes(regionSlug));
}

export function tripsOfType(type: RoadTrip["type"]): RoadTrip[] {
  return roadTrips.filter((t) => t.type === type);
}

/** Day plans with an e-bike component, for chips and filters. */
export function eBikeDays(trip: RoadTrip): DayPlan[] {
  return trip.itinerary.filter((d) => d.eBikeDay);
}
