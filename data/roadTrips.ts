/** "2h15" → 2.25, "45min" → 0.75, "—" → 0. */
export function driveTimeToHours(t: string): number {
  const h = /(\d+)\s*h\s*(\d+)?/.exec(t);
  if (h) return Number(h[1]) + (h[2] ? Number(h[2]) / 60 : 0);
  const m = /(\d+)\s*min/.exec(t);
  return m ? Number(m[1]) / 60 : 0;
}

type TripInput = Omit<RoadTrip, "totalKm" | "avgDailyDriveHours">;

/**
 * Derives totalKm (sum of daily km) and avgDailyDriveHours (mean over days
 * with any driving, rounded to the nearest half hour) from the itinerary,
 * so the key facts can never drift from the day-by-day plan.
 */
function defineTrip(t: TripInput): RoadTrip {
  const totalKm = t.itinerary.reduce((sum, d) => sum + d.km, 0);
  const driving = t.itinerary.filter((d) => d.km > 0);
  const hours = driving.reduce((sum, d) => sum + driveTimeToHours(d.driveTime), 0);
  const avg = driving.length ? Math.round((hours / driving.length) * 2) / 2 : 0;
  return { ...t, totalKm, avgDailyDriveHours: avg };
}

function tripImages(
  region: string,
  heroKeys: string[],
  hoverKeys: string[],
  galleryKeys: string[],
  /** Override the poster card image (e.g. when two trips share a region). */
  cardKeys: string[] = [],
): Pick<RoadTrip, "heroImage" | "cardImage" | "hoverImage" | "gallery"> {
  const r = `region:${region}`;
  const gallery: Img[] = galleryKeys.map((k, i) => photo([k, r], i % 3));
  return {
    heroImage: photo([...heroKeys, r], 0),
    cardImage: photo([...cardKeys, `${r}:portrait`, r], 0),
    hoverImage: photo([...hoverKeys, r], 1),
    gallery,
  };
}

